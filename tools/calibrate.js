#!/usr/bin/env node
/*
 calibrate.js - calibrates the width of the app's 95% prediction range.

 Run after fetch_giovanni.py / fetch_appeears.py:   node tools/calibrate.js
 Writes data/calibration.js.

 Method: for every place and variable, the app's own prediction code (read from index.html, section 4b) is refitted
 without the last five years, and the error of each hidden year is divided by the uncalibrated half-width of the
 range at that year. For each variable the 95th percentile of these ratios becomes the factor that multiplies the
 range (bounded to 0.8-3), so that across all places 95% of hidden years fall inside it. The coverage before and after
 is stored and shown on the app's Data & Methods page.
*/
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const grab = (a, b) => src.slice(src.indexOf(a), src.indexOf(b, src.indexOf(a))).replace(/^const /gm, 'var ').replace(/^let /gm, 'var ');
const load = f => { const t = fs.readFileSync(path.join(root, 'data', f), 'utf8'); const i = t.indexOf('=') + 1, j = t.lastIndexOf(';'); return JSON.parse(t.slice(i, j)); };
const D = load('observations.js');
let N = null; try { N = load('ndvi.js'); } catch (_) { N = null; }
var YEAR_END = D.year_end, Y0 = 1980, BASE0 = 2005, BASE1 = 2020, VARS = {}, CAL = null;
eval(grab('const range=', 'function fmt('));
eval(grab('const mean=', 'const store='));
eval(grab('function lgamma', '/* =====================================================================\n   4b.'));
eval(grab('const QC_RANGE=', '/* =====================================================================\n   5. DATA'));

const ratios = {}, cover = {};
function run(id, s, mb) {
  const d = {}; d[id] = { start: Y0, vals: range(Y0, YEAR_END).map(y => { const x = s.vals[y - s.start]; return x == null ? null : x; }), mon: mb ? { start: mb.start, vals: mb.vals } : null };
  const P = predict(d, id); if (!P.ok) return;
  P.test.forEach(q => { const h = P.tr.half(q.y); if (h > 0) (ratios[id] = ratios[id] || []).push(Math.abs(q.v - q.p) / h); });
}
for (const site of Object.values(D.sites)) for (const id of Object.keys(site.series)) run(id, site.series[id], site.monthly[id]);
if (N) for (const s of Object.values(N.sites)) run('ndvi', s, s.monthly);

const factor = {};
for (const [id, r] of Object.entries(ratios)) {
  r.sort((a, b) => a - b);
  const q95 = r[Math.min(r.length - 1, Math.floor(0.95 * r.length))], f = Math.min(3, Math.max(0.8, q95));
  factor[id] = +f.toFixed(3);
  cover[id] = { tests: r.length, before: +(100 * r.filter(x => x <= 1).length / r.length).toFixed(1), after: +(100 * r.filter(x => x <= f).length / r.length).toFixed(1) };
  console.log(id.padEnd(7), 'hidden years', r.length, '| inside before', cover[id].before + '%', '| factor', factor[id], '| inside after', cover[id].after + '%');
}
const out = { made: D.retrieved, note: 'Width factors for the 95% prediction range, from five-year backtests at every place (tools/calibrate.js).', factor, coverage: cover };
fs.writeFileSync(path.join(root, 'data', 'calibration.js'), '/* Generated by tools/calibrate.js. Do not edit by hand. */\nwindow.ETD_CAL=' + JSON.stringify(out) + ';\n');
console.log('wrote data/calibration.js');
